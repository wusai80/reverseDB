"""Regenerate three-subject paper tables from frozen evidence; no benchmarks."""
import hashlib
import json
from pathlib import Path
import statistics

ROOT = Path(__file__).resolve().parents[1]

def load(name):
    return json.loads((ROOT/name).read_text())

def median(xs):
    return statistics.median(xs)

def contrast(original, candidate):
    assert len(original) == len(candidate)
    return dict(original_ms=median(original), candidate_ms=median(candidate),
        ratio_of_medians=median(original)/median(candidate),
        reduction_percent=100*(1-median(candidate)/median(original)),
        median_paired_ratio=median(a/b for a,b in zip(original,candidate)),
        wins=sum(b<a for a,b in zip(original,candidate)), blocks=len(original))

def table(command, columns, header, rows):
    return '\\newcommand{\\'+command+'}{%\n\\begin{tabular}{@{}'+columns+'@{}}\n\\toprule\n'+header+' \\\\\n\\midrule\n'+'\n'.join(' & '.join(row)+' \\\\' for row in rows)+'\n\\bottomrule\n\\end{tabular}\n}\n'

def build():
    inputs = ['evidence/tpcc-contract-slice/20261110-72f5adabbcb5/run.json',
        'evidence/fossil-hash-slice/20261110-v2/summary.json',
        'evidence/oscar-ordered-handoff-performance/20261108-9f48de23db45/summary.json',
        'evidence/fusion-ablation/20261109-387e2307dcc2/summary.json']
    for freeze in ['tpcc-contract-slice','fossil-hash-slice','adaptive-planning','adaptive-planning-api']:
        path=f'paper/{freeze}-freeze.json';inputs.append(path)
        for p,digest in load(path)['sha256'].items():
            assert hashlib.sha256((ROOT/p).read_bytes()).hexdigest()==digest,p
    tpcc=load(inputs[0]); fossils=load(inputs[1]); oscar=load(inputs[2])
    arms={}
    for arm in ['original','slice_only','fusion_only','fusion_slice']:
        runs=sorted([r for r in tpcc['cases'] if r['phase']=='measurement' and r['arm']==arm],key=lambda r:r['round'])
        assert len(runs)==8
        arms[arm]=dict(blocks=[r['round'] for r in runs],
            mixed_ms=[sum(s['duration_ns'] for s in r['samples'])/1e6 for r in runs],
            orderstatus_ms=[sum(s['duration_ns'] for s in r['samples'] if s['type']=='OrderStatus')/1e6 for r in runs],
            calls=[sum(s['execute_calls'] for s in r['samples']) for r in runs])
    for a in arms.values():assert a['blocks']==arms['original']['blocks']
    java=contrast(arms['original']['mixed_ms'],arms['fusion_only']['mixed_ms'])
    fossil={}
    for scenario in fossils['performance']:
        values={arm:[b['runs'][arm]['elapsed_ms'] for b in scenario['blocks']] for arm in ['original','roundtrip','slice']}
        assert len(values['original'])==12
        fossil[scenario['name']]=dict(contrast(values['original'],values['slice']),roundtrip_ms=median(values['roundtrip']))
    negative=contrast([p['original_ms'] for p in oscar['pairs']],[p['candidate_ms'] for p in oscar['pairs']])
    assert abs(negative['ratio_of_medians']-oscar['ratio_of_medians'])<1e-12
    result=dict(schema='paper-three-subject-results/v1',date='2026-11-10',
        subjects={'java':dict(outcome='success',mechanism='fusion',performance=java),
                  'fossil':dict(outcome='success',mechanism='contract-rooted deletion',performance=fossil),
                  'oscar':dict(outcome='no stable gain; current gate abstains',performance=negative,
                      paired_interval=oscar['exploratory_bootstrap_95'],candidate_status='historical experimental adapter; not admitted by current gate')},
        java_four_arm=arms,composition_increment=contrast(arms['fusion_only']['mixed_ms'],arms['fusion_slice']['mixed_ms']),
        selectors={},new_performance_measurements=False,
        case_selection='Purposively selected two positive and one negative case; not a success-rate estimate')
    rows=[]
    for label,r in [('Java fusion',java),('Fossil hash',fossil['hash']),('Fossil branch',fossil['branch']),('Oscar experimental adapter',negative)]:
        rows.append([label,f"{r['original_ms']:.3f}",f"{r['candidate_ms']:.3f}",f"${r['ratio_of_medians']:.3f}\\times$",f"{r['wins']}/{r['blocks']}"])
    tex='% Generated by scripts/update_paper_results.py from archived raw measurements.\n'
    tex+=table('PrimaryResults','lrrrr','Workload & Original & Candidate & Median ratio & Wins',rows)
    rows=[]
    for name,label in [('original','Original'),('slice_only','Deletion only'),('fusion_only','Fusion only'),('fusion_slice','Fusion + deletion')]:
        r=arms[name];assert len(set(r['calls']))==1
        rows.append([label,f"{median(r['mixed_ms']):.3f}",f"{median(r['orderstatus_ms']):.3f}",str(r['calls'][0])])
    tex+=table('JavaCompositionResults','lrrr','Plan & Mixed ms & OrderStatus ms & JDBC calls',rows)
    rows=[]
    for name,label in [('fossil-hash','Fossil hash'),('fossil-branch','Fossil branch'),('tpcc-mixed','Java mixed'),('oscar-prefix','Oscar prefix')]:
        path=f'evidence/adaptive-planning/20261110-v2/{name}/selection.json';inputs.append(path)
        r=load(path);result['selectors'][name]=r
        names={'slice':'Deletion','fusion_only':'Fusion','original':'Original'}
        if r['selected']=='original':gain=lower='---'
        else:
            pair=r['comparisons'][r['selected']+'>original'];gain=f"{pair['geometric_speedup']:.3f}";lower=f"{pair['lower_speedup']:.3f}"
        rows.append([label,names[r['selected']],gain,lower])
    tex+=table('SelectionResults','llrr','Context & Choice & Geometric ratio & Lower bound',rows)
    java_ablation=load(inputs[3])['all']['factorial'];rows=[]
    for arm,label,calls in [('original','Original',267),('query_only','NewOrder only',94),('model_only','Payment only',262),('full','Both',89)]:
        ratio='---' if arm=='original' else f"${java_ablation['comparisons']['original__'+arm]['median']:.3f}\\times$"
        rows.append([label,str(calls),f"{java_ablation['arm_median_ms'][arm]:.3f}",ratio])
    tex+=table('JavaRegionResults','lrrr','Plan & JDBC calls & Median ms & Paired ratio',rows)
    result['source_sha256']={p:hashlib.sha256((ROOT/p).read_bytes()).hexdigest() for p in inputs}
    (ROOT/'paper/results.json').write_text(json.dumps(result,indent=2)+'\n')
    (ROOT/'paper/results-tables.tex').write_text(tex)
    print(json.dumps({k:v['performance'] for k,v in result['subjects'].items()},indent=2))

if __name__=='__main__':build()
